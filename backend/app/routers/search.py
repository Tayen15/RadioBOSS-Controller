"""Search and URL Resolution Router."""
import logging
from fastapi import APIRouter, HTTPException
from app.config import get_settings
from app.schemas.track import (
    SearchRequest,
    SearchResponse,
    ResolveRequest,
    ResolveResponse,
)
from app.services.ytmusic_service import ytmusic_service
from app.services.ytdlp_service import ytdlp_service

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/api", tags=["Search & Resolution"])


@router.post("/search", response_model=SearchResponse)
async def search_songs(request: SearchRequest):
    """
    Search YouTube Music specifically for official studio master tracks.
    Filters exclusively for song items (Topic / Auto-generated by YouTube).
    """
    try:
        results = ytmusic_service.search_songs(query=request.query, limit=request.limit)
        return SearchResponse(
            success=True,
            query=request.query,
            results=results,
        )
    except Exception as e:
        logger.error(f"Search endpoint error: {e}")
        raise HTTPException(status_code=500, detail=f"Gagal melakukan pencarian: {str(e)}")


@router.post("/resolve", response_model=ResolveResponse)
async def resolve_url(request: ResolveRequest):
    """
    Resolve a YouTube or YouTube Music URL or video ID directly.
    Extracts metadata and returns both direct stream URL and anti-expiry relay URL.
    """
    settings = get_settings()
    try:
        track, direct_url = ytdlp_service.extract_track_info(request.url)
        if not track:
            return ResolveResponse(
                success=False,
                error="Tidak dapat menemukan atau memproses audio dari URL ini. Pastikan link YouTube valid.",
            )

        relay_url = f"http://{settings.SERVER_HOST}:{settings.SERVER_PORT}/api/stream/{track.video_id}"

        return ResolveResponse(
            success=True,
            data=track,
            direct_stream_url=direct_url,
            relay_stream_url=relay_url,
        )
    except Exception as e:
        logger.error(f"Resolve endpoint error: {e}")
        return ResolveResponse(
            success=False,
            error=f"Error saat mengekstrak link: {str(e)}",
        )


@router.get("/lyrics/{video_id}")
async def get_lyrics(video_id: str):
    """
    Retrieve real-time lyrics and announcer talking points / cues
    for the specified YouTube Music track.
    """
    clean_id = video_id.replace(".mp3", "").strip()
    try:
        import asyncio
        data = await asyncio.to_thread(
            ytmusic_service.get_lyrics_and_talking_points,
            clean_id,
        )
        return data
    except Exception as e:
        logger.error(f"Error fetching lyrics for {clean_id}: {e}")
        raise HTTPException(status_code=500, detail=f"Gagal mengambil lirik: {str(e)}")
